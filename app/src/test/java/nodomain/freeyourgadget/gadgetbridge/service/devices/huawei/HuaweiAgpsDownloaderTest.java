    // Synthetic RTCM frame. The CRC24Q is independently fixed, not generated by the parser.
    private static final byte[] FRAME = gpsFrame();
    private static final String SEED_URL = "https://configdownload-dre.dbankcdn.com/update/Higeo/"
            + "0".repeat(64) + "/HiEE_V2.dat";
    private static final byte[] SEED = "abc".getBytes(StandardCharsets.UTF_8);
    // SHA-256 of the independent test vector "abc42".
    private static final String SEED_SIGNATURE = "8216ac77f5c9ed66907b03f1d78b795e7cdd315cecd13df42cd7245d45e16b06";

    private static byte[] gpsFrame() {
        final byte[] frame = new byte[67];
        frame[0] = (byte) 0xd3;
        frame[2] = 61;
        frame[3] = 0x3f;
        frame[4] = (byte) 0xb0;
        frame[63] = 1;
        frame[64] = (byte) 0xc6;
        frame[65] = (byte) 0xee;
        frame[66] = (byte) 0xf5;
        return frame;
    }

    @Test
    public void supportsOnlyTheVerifiedTagAndVersion() {
        assertTrue(HuaweiAgpsDownloader.supports(3, HuaweiAgpsDownloader.TAG));
        assertTrue(HuaweiAgpsDownloader.supports(3, HuaweiAgpsDownloader.PGNSS_TAG));
        assertFalse(HuaweiAgpsDownloader.supports(2, HuaweiAgpsDownloader.PGNSS_TAG));
        assertFalse(HuaweiAgpsDownloader.supports(2, HuaweiAgpsDownloader.TAG));
        assertFalse(HuaweiAgpsDownloader.supports(3, null));
        assertFalse(HuaweiAgpsDownloader.supports(3, HuaweiAgpsDownloader.TAG + ";"));
        assertFalse(HuaweiAgpsDownloader.supports(3, "com.huawei.higeo_dataModule_PGNSSConfig?type=HW_EEV2/HW_PGNSS_PRED"));
    }

    @Test
    public void acceptsRawAndGzipFramesWithoutChangingBytes() throws Exception {
        assertArrayEquals(FRAME, decode(FRAME));
        assertArrayEquals(FRAME, decode(gzip(FRAME)));
        final byte[] allTypes = HuaweiAgpsFileGenerator.generateRtcm(List.of(
                payload(1019, 61), payload(1020, 45), payload(1042, 64), payload(1046, 63)));
        assertArrayEquals(allTypes, decode(gzip(allTypes)));
    }

    @Test
    public void rejectsEmptyMalformedAndTruncatedFrames() {
        for (int length = 0; length < FRAME.length; length++) {
            final byte[] truncated = Arrays.copyOf(FRAME, length);
            assertThrows(IOException.class, () -> decode(truncated));
        }
        final byte[] badPreamble = FRAME.clone();
        badPreamble[0] = 0;
        assertThrows(IOException.class, () -> decode(badPreamble));
        final byte[] reservedBits = FRAME.clone();
        reservedBits[1] = 4;
        assertThrows(IOException.class, () -> decode(reservedBits));
        final byte[] shortPayload = FRAME.clone();
        shortPayload[2] = 1;
        assertThrows(IOException.class, () -> decode(shortPayload));
        assertThrows(IOException.class, () -> decode(Arrays.copyOf(FRAME, FRAME.length + 1)));
    }

    @Test
    public void rejectsWrongChecksumsAndUnsupportedMessages() {
        final byte[] damaged = FRAME.clone();
        damaged[6] ^= 1;
        assertThrows(IOException.class, () -> decode(damaged));
        final byte[] wrongCrc = FRAME.clone();
        wrongCrc[wrongCrc.length - 1] ^= 1;
        assertThrows(IOException.class, () -> decode(wrongCrc));
        final byte[] unknownType = HuaweiAgpsFileGenerator.generateRtcm(List.of(new byte[]{0x40, 0x20}));
        assertThrows(IOException.class, () -> decode(unknownType));
    }

    @Test
    public void rejectsWrongPayloadLengthsEvenWithValidChecksums() {
        // This independent CRC24Q vector has a valid frame but an incomplete GPS payload.
        final byte[] shortFrame = {(byte) 0xd3, 0, 4, 0x3f, (byte) 0xb0, 0, 1,
                (byte) 0xdf, 0x2f, (byte) 0xc6};
        assertThrows(IOException.class, () -> decode(shortFrame));
        final int[][] formats = {{1019, 61}, {1020, 45}, {1042, 64}, {1046, 63}};
        for (final int[] format : formats) {
            for (final int length : new int[]{format[1] - 1, format[1] + 1}) {
                final byte[] frame = HuaweiAgpsFileGenerator.generateRtcm(List.of(payload(format[0], length)));
                assertThrows(IOException.class, () -> decode(frame));
            }
        }
    }

    @Test
    public void rejectsTruncatedOrCorruptGzip() throws Exception {
        final byte[] compressed = gzip(FRAME);
        assertThrows(IOException.class, () -> decode(Arrays.copyOf(compressed, compressed.length - 1)));
        compressed[compressed.length - 8] ^= 1;
        assertThrows(IOException.class, () -> decode(compressed));
    }

    @Test
    public void boundsBothDownloadedAndExpandedBytes() throws Exception {
        assertThrows(IOException.class, () -> decode(new byte[HuaweiAgpsDownloader.MAX_RESPONSE_BYTES + 1]));
        final byte[] expanded = new byte[HuaweiAgpsDownloader.MAX_RTCM_BYTES + 1];
        final byte[] compressed = gzip(expanded);
        assertTrue(compressed.length < HuaweiAgpsDownloader.MAX_RESPONSE_BYTES);
        final IOException failure = assertThrows(IOException.class, () -> decode(compressed));
        assertTrue(failure.getMessage().contains("size limit"));
    }

