    @Test
    public void replacingADownloadSuppressesThePreviousResponse() throws Exception {
        final ArrayBlockingQueue<HuaweiAgpsDownloader.ResponseCallback> callbacks = new ArrayBlockingQueue<>(2);
        final HuaweiAgpsDownloader downloader = new HuaweiAgpsDownloader((url, headers, callback) -> callbacks.add(callback), 5_000);
        final Result first = new Result();
        final Result second = new Result();
        try {
            downloader.download(first);
            final HuaweiAgpsDownloader.ResponseCallback firstCallback = callbacks.poll(2, TimeUnit.SECONDS);
            assertTrue(firstCallback != null);
            downloader.download(second);
            final HuaweiAgpsDownloader.ResponseCallback secondCallback = callbacks.poll(2, TimeUnit.SECONDS);
            assertTrue(secondCallback != null);
            final TrackingStream late = new TrackingStream(FRAME);
            firstCallback.onResponse(200, late);
            assertTrue(late.closed);
            secondCallback.onResponse(200, new TrackingStream(FRAME));
            second.await();
            assertArrayEquals(FRAME, second.bytes);
            assertEquals(0, first.calls.get());
            assertEquals(1, second.calls.get());
        } finally {
            downloader.dispose();
        }
    }

