    @Test
    public void downloadsTheManifestThenSeedAndClosesBothBeforeConversion() throws Exception {
        final QueuedTransport transport = new QueuedTransport();
        final DatasetResult result = new DatasetResult();
        final TrackingStream manifestBody = new TrackingStream(manifest());
        final TrackingStream seedBody = new TrackingStream(SEED);
        final Map<String, byte[]> files = Map.of("HW_PGNSS_GPS", new byte[]{1});
        final HuaweiAgpsDownloader downloader = new HuaweiAgpsDownloader(transport, 5_000, (seed, time) -> {
            assertTrue(manifestBody.closed);
            assertTrue(seedBody.closed);
            assertArrayEquals(SEED, seed);
            assertEquals(123456789L, time);
            return files;
        }, () -> 123456789L);
        try {
            downloader.download(HuaweiAgpsDownloader.PGNSS_TAG, result);
            final Exchange manifestRequest = transport.await();
            assertEquals(HuaweiAgpsDownloader.PGNSS_MANIFEST_URL, manifestRequest.url());
            assertEquals("HealthApp", manifestRequest.headers().get("App-ID"));
            assertTrue(manifestRequest.headers().containsKey("traceId"));
            manifestRequest.callback().onResponse(200, manifestBody);
            final Exchange seedRequest = transport.await();
            assertEquals(SEED_URL, seedRequest.url());
            assertTrue(seedRequest.headers().isEmpty());
            seedRequest.callback().onResponse(200, seedBody);
            result.await();
            assertEquals(files, result.files);
            assertEquals(1, result.calls.get());
            assertFalse(result.interrupted);
        } finally {
            downloader.dispose();
        }
    }

